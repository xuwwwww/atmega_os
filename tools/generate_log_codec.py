#!/usr/bin/env python3
"""Generate AVR PROGMEM Huffman messages and the host-side decoder table."""

import argparse
import heapq
import json
from collections import Counter
from pathlib import Path


def parse_args():
    parser = argparse.ArgumentParser()
    parser.add_argument("--manifest", required=True)
    parser.add_argument("--c-source", required=True)
    parser.add_argument("--c-header", required=True)
    parser.add_argument("--python", required=True)
    return parser.parse_args()


def build_codes(messages):
    frequencies = Counter()
    for message in messages.values():
        frequencies.update(message.encode("utf-8"))

    heap = []
    serial = 0
    for symbol, frequency in sorted(frequencies.items()):
        heapq.heappush(heap, (frequency, symbol, serial, symbol))
        serial += 1

    if not heap:
        raise ValueError("the log message manifest is empty")

    while len(heap) > 1:
        left = heapq.heappop(heap)
        right = heapq.heappop(heap)
        node = (left[3], right[3])
        heapq.heappush(
            heap,
            (left[0] + right[0], min(left[1], right[1]), serial, node),
        )
        serial += 1

    codes = {}

    def visit(node, bits):
        if isinstance(node, int):
            codes[node] = bits or "0"
            return
        visit(node[0], bits + "0")
        visit(node[1], bits + "1")

    visit(heap[0][3], "")
    return codes


def encode(data, codes):
    bits = "".join(codes[byte] for byte in data)
    padded = bits + "0" * ((8 - len(bits) % 8) % 8)
    payload = [int(padded[i : i + 8], 2) for i in range(0, len(padded), 8)]
    return payload, len(bits)


def write_outputs(messages, codes, c_source_path, c_header_path, python_path):
    encoded = {
        name: encode(text.encode("utf-8"), codes)
        for name, text in messages.items()
    }

    header_lines = [
        "#ifndef GENERATED_LOG_MESSAGES_H",
        "#define GENERATED_LOG_MESSAGES_H",
        "",
        "#include <avr/pgmspace.h>",
        "#include <stdint.h>",
        "",
    ]
    source_lines = [
        '#include "log_messages.h"',
        "",
    ]

    for name, (payload, bit_count) in encoded.items():
        symbol = name.lower()
        byte_count = len(payload)
        header_lines.extend(
            [
                f"extern const uint8_t {symbol}_data[{byte_count}] PROGMEM;",
                f"#define {name}_BYTE_COUNT {byte_count}u",
                f"#define {name}_BIT_COUNT {bit_count}u",
                "",
            ]
        )
        byte_text = ", ".join(f"0x{byte:02x}" for byte in payload)
        source_lines.extend(
            [
                f"const uint8_t {symbol}_data[{byte_count}] PROGMEM =",
                "{",
                f"    {byte_text}",
                "};",
                "",
            ]
        )

    header_lines.append("#endif")
    header_lines.append("")

    python_lines = [
        '"""Generated by generate_log_codec.py; do not edit manually."""',
        "",
        "DECODE_TABLE = {",
    ]
    for symbol, bits in sorted(codes.items(), key=lambda item: (len(item[1]), item[1])):
        python_lines.append(f"    ({int(bits, 2)}, {len(bits)}): {symbol},")
    python_lines.extend(["}", ""])

    outputs = (
        (c_header_path, "\n".join(header_lines)),
        (c_source_path, "\n".join(source_lines)),
        (python_path, "\n".join(python_lines)),
    )
    for path, content in outputs:
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(content, encoding="utf-8")


def main():
    args = parse_args()
    manifest_path = Path(args.manifest)
    messages = json.loads(manifest_path.read_text(encoding="utf-8"))
    codes = build_codes(messages)
    write_outputs(
        messages,
        codes,
        Path(args.c_source),
        Path(args.c_header),
        Path(args.python),
    )


if __name__ == "__main__":
    main()
